export function formatPrice(value) {
  return new Intl.NumberFormat('en-NG', {
    style: 'currency',
    currency: 'NGN',
    maximumFractionDigits: 0,
  }).format(value);
}

export function formatCategoryLabel(value) {
  return categoryOptions
    .find((option) => option.value === value)?.label || 'Product';
}

export function buildProductUrl(product) {
  return `/products/${product.category}/${product.id}`;
}
